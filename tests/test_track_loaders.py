# All three loaders must agree
def test_every_loader_produces_the_same_lineage_numbering(
    tmp_path, ctc_folder, btrack_lineage
):
    """CTC, Ultrack and btrack must not disagree about TrackNumber.

    The lineage editing tools (division, split, fuse, undo) navigate the
    TrackNumber tree arithmetically, so a loader that numbered differently
    would silently corrupt edits made after that import.
    """
    ctc = ctc_to_long(ctc_folder)
    ultrack = load_ultrack_with_tracknumber(
        write_ultrack_folder(tmp_path / "cmp", ultrack_frame())
    )
    btrack_df = tracks_to_dataframe(btrack_lineage)

    def spans(df):
        grouped = df.groupby("TrackNumber")["t"].agg(["min", "max"])
        return {int(k): tuple(v) for k, v in grouped.iterrows()}

    assert spans(ctc) == spans(ultrack) == spans(btrack_df)
    assert spans(ctc) == {1: (0, 2), 2: (3, 5), 3: (3, 5)}


# Collecting several positions
def test_collect_positions_reads_every_position_folder(tmp_path):
    parent = tmp_path / "experiment"
    for position in (1, 2):
        write_ctc_folder(parent / f"exp_p{position}", DIVIDING_RES_TRACK)

    df = collect_positions_to_track_df_parallel(str(parent), "CTC", workers=2)

    assert sorted(df["Position"].unique()) == [1, 2]
    assert len(df) == 18


def test_collect_positions_tags_rows_with_the_folder_position_number(tmp_path):
    parent = tmp_path / "experiment"
    write_ctc_folder(parent / "exp_p7", DIVIDING_RES_TRACK)

    df = collect_positions_to_track_df_parallel(str(parent), "CTC")

    assert df["Position"].unique().tolist() == [7]


def test_collect_positions_skips_folders_without_a_position_suffix(tmp_path):
    parent = tmp_path / "experiment"
    write_ctc_folder(parent / "exp_p1", DIVIDING_RES_TRACK)
    (parent / "Analysis").mkdir()  # no _p<number> suffix

    df = collect_positions_to_track_df_parallel(str(parent), "CTC")

    assert df["Position"].unique().tolist() == [1]


def test_collect_positions_of_nothing_returns_an_empty_frame(tmp_path):
    parent = tmp_path / "empty"
    parent.mkdir()

    assert collect_positions_to_track_df_parallel(str(parent), "CTC").empty


def test_collect_positions_supports_the_ultrack_format(tmp_path):
    parent = tmp_path / "experiment"
    write_ultrack_folder(parent / "exp_p3", ultrack_frame())

    df = collect_positions_to_track_df_parallel(str(parent), "Ultrack")

